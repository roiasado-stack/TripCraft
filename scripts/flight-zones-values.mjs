// Builds the airport → time-zone map for docs/plans/2026-11-16-flight-zones-backfill.sql
// (STEP 1) from the airport texts actually stored in a database.
//
//   node scripts/flight-zones-values.mjs airports.csv > flight-zone-map.sql
//
// airports.csv is STEP 0's result, exported from the SQL Editor ("Download CSV"): a header
// row, then one airport text per row in the first column ("Bangkok (BKK)", "נתב\"ג", "TLV").
// Extra columns (the count) are ignored.
//
// Each text goes through the app's own iataOf() and zoneOf() (supabase/functions/_shared),
// so the backfill resolves exactly what the app's writers will. A text with no recognisable
// code, or a code with no known zone, is printed as a comment and left out — never guessed.
// Prints SQL only; touches no database. Needs Node 22.18+ (runs the .ts modules directly).
import { readFileSync } from "node:fs";
import { basename } from "node:path";
import { iataOf } from "../supabase/functions/_shared/flight-time.ts";
import { zoneOf } from "../supabase/functions/_shared/airport-zones.ts";

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/flight-zones-values.mjs <airports.csv>");
  process.exit(2);
}

// RFC 4180: quoted fields may hold commas, newlines and doubled quotes.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else field += c;
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const sqlText = (s) => `'${s.replace(/'/g, "''")}'`;
// A comment line must not be able to end early or smuggle SQL onto a new line.
const commentText = (s) => s.replace(/[\r\n]+/g, " ");

const texts = [
  ...new Set(
    parseCsv(readFileSync(file, "utf8").replace(/^﻿/, ""))
      .slice(1) // header
      .map((r) => r[0])
      .filter((t) => typeof t === "string" && t.trim() !== ""),
  ),
].sort();

const resolved = [];
const unresolved = [];
for (const text of texts) {
  const code = iataOf(text);
  const zone = code ? zoneOf(code) : null;
  if (zone) resolved.push({ text, code, zone });
  else unresolved.push({ text, why: code ? `code ${code} has no known zone` : "no airport code recognised" });
}

const out = [];
out.push(`-- Generated by scripts/flight-zones-values.mjs from ${commentText(basename(file))}.`);
out.push(`-- ${resolved.length} airport texts resolved, ${unresolved.length} left without a zone.`);
out.push("CREATE TABLE IF NOT EXISTS ops.flight_zone_map (airport TEXT PRIMARY KEY, iata TEXT NOT NULL, zone TEXT NOT NULL);");
out.push("TRUNCATE ops.flight_zone_map;");
if (resolved.length) {
  out.push("INSERT INTO ops.flight_zone_map (airport, iata, zone) VALUES");
  out.push(resolved.map((r) => `  (${sqlText(r.text)}, ${sqlText(r.code)}, ${sqlText(r.zone)})`).join(",\n") + ";");
}
if (unresolved.length) {
  out.push("-- Left out (their flights keep from_tz / to_tz NULL: ticket time shown, no duration):");
  for (const u of unresolved) out.push(`--   ${commentText(u.text)}  (${u.why})`);
}
console.log(out.join("\n"));
